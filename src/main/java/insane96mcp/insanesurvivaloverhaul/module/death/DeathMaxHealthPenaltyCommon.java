package insane96mcp.insanesurvivaloverhaul.module.death;

import insane96mcp.insanelib.core.feature.ConfigType;
import insane96mcp.insanelib.core.feature.Feature;
import insane96mcp.insanelib.core.feature.LoadFeature;
import insane96mcp.insanelib.core.feature.Module;
import insane96mcp.insanesurvivaloverhaul.InsaneSO;
import insane96mcp.insanesurvivaloverhaul.module.ISOModules;
import insane96mcp.insanesurvivaloverhaul.module.misc.Packs;
import net.neoforged.fml.config.ModConfig;

@ConfigType(ModConfig.Type.COMMON)
@LoadFeature(module = ISOModules.DEATH, description = "Enables the data pack of Death Max Health Penalty.")
public class DeathMaxHealthPenaltyCommon extends Feature {
	@Override
	public void init(Module module, boolean enabledByDefault, boolean canBeDisabled) {
		super.init(module, enabledByDefault, canBeDisabled);
		InsaneSO.addServerPack("max_health_death_penalty", "Insane's Survival Overhaul Max Health Death Penalty", () -> this.isEnabled() && !Packs.disableAllDataPacks);
	}
}
